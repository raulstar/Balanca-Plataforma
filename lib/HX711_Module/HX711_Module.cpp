/////////////////////////////////////////////////////////////////////////////
// VARIÁVEIS GLOBAIS
/////////////////////////////////////////////////////////////////////////////

float plataforma1 = 0.0f;

/////////////////////////////////////////////////////////////////////////////
// CONSTRUTOR HX711
/////////////////////////////////////////////////////////////////////////////

HX711::HX711()
{
    offset = 0.0f;

    //////////////////////////////////////////////////////////////////////////
    // FATOR PADRÃO
    //////////////////////////////////////////////////////////////////////////

    scale_factor = -4782.34179688f;
}

/////////////////////////////////////////////////////////////////////////////
// TARA
/////////////////////////////////////////////////////////////////////////////

void HX711::tare(float leituraAtual)
{
    offset = leituraAtual;

    Serial.println("OFFSET:");
    Serial.println(offset);
}

/////////////////////////////////////////////////////////////////////////////
// LEITURA EM UNIDADES
/////////////////////////////////////////////////////////////////////////////

float HX711::get_units(float leituraAtual)
{
    plataforma1 = (leituraAtual - offset) * scale_factor;

    return plataforma1;
}

/////////////////////////////////////////////////////////////////////////////
// CALIBRAÇÃO
/////////////////////////////////////////////////////////////////////////////

void HX711::calibra(float leituraAtual, float known_weight)
{
    //////////////////////////////////////////////////////////////////////////
    // LEITURA LÍQUIDA
    //////////////////////////////////////////////////////////////////////////

    float leituraLiquida = leituraAtual - offset;

    //////////////////////////////////////////////////////////////////////////
    // DEBUG
    //////////////////////////////////////////////////////////////////////////

    Serial.println("--------------------------------");

    Serial.print("OFFSET: ");
    Serial.println(offset, 6);

    Serial.print("LEITURA: ");
    Serial.println(leituraAtual, 6);

    Serial.print("LIQUIDA: ");
    Serial.println(leituraLiquida, 6);

    //////////////////////////////////////////////////////////////////////////
    // PROTEÇÃO DIVISÃO ZERO
    //////////////////////////////////////////////////////////////////////////

    if (fabs(leituraLiquida) < 0.0001f)
    {
        Serial.println("ERRO: PESO INVALIDO");

        return;
    }

    //////////////////////////////////////////////////////////////////////////
    // CALIBRAÇÃO
    //////////////////////////////////////////////////////////////////////////

    scale_factor = known_weight / leituraLiquida;

    //////////////////////////////////////////////////////////////////////////
    // RESULTADO
    //////////////////////////////////////////////////////////////////////////

    Serial.print("FACTOR: ");
    Serial.println(scale_factor, 8);

    Serial.println("--------------------------------");
}

/////////////////////////////////////////////////////////////////////////////
// CONSTRUTOR SENSOR BALANÇA
/////////////////////////////////////////////////////////////////////////////

SensorBalanca::SensorBalanca(HardwareSerial &porta)
{
    serial = &porta;
}

/////////////////////////////////////////////////////////////////////////////
// LEITURA SENSOR
/////////////////////////////////////////////////////////////////////////////

bool SensorBalanca::leitura()
{
    while (serial->available())
    {
        char c = serial->read();

        //////////////////////////////////////////////////////////////////////////
        // IGNORA CR
        //////////////////////////////////////////////////////////////////////////

        if (c == '\r')
        {
            continue;
        }

        //////////////////////////////////////////////////////////////////////////
        // FIM DA LINHA
        //////////////////////////////////////////////////////////////////////////

        if (c == '\n')
        {
            rxBuffer[rxIndex] = '\0';

            //////////////////////////////////////////////////////////////////////////
            // CONVERSÃO
            //////////////////////////////////////////////////////////////////////////

            valorLido = atof(rxBuffer);

            //////////////////////////////////////////////////////////////////////////
            // RESET BUFFER
            //////////////////////////////////////////////////////////////////////////

            rxIndex = 0;

            //////////////////////////////////////////////////////////////////////////
            // IGNORA ZERO
            //////////////////////////////////////////////////////////////////////////

            if (fabs(valorLido) < 0.0001f)
            {
                ready = false;

                return false;
            }

            //////////////////////////////////////////////////////////////////////////
            // PESO
            //////////////////////////////////////////////////////////////////////////

            pesoGramas = balanca.get_units(valorLido);

            pesoKg = pesoGramas / 1000.0f;

            //////////////////////////////////////////////////////////////////////////
            // STATUS
            //////////////////////////////////////////////////////////////////////////

            ready = true;

            return true;
        }

        //////////////////////////////////////////////////////////////////////////
        // BUFFER RX
        //////////////////////////////////////////////////////////////////////////

        else
        {
            if (rxIndex < sizeof(rxBuffer) - 1)
            {
                rxBuffer[rxIndex++] = c;
            }
        }
    }

    return false;
}

/////////////////////////////////////////////////////////////////////////////
// STATUS
/////////////////////////////////////////////////////////////////////////////

bool SensorBalanca::isReady()
{
    return ready;
}

/////////////////////////////////////////////////////////////////////////////
// RAW
/////////////////////////////////////////////////////////////////////////////

float SensorBalanca::getRaw()
{
    return valorLido;
}

/////////////////////////////////////////////////////////////////////////////
// KG
/////////////////////////////////////////////////////////////////////////////

float SensorBalanca::getKg()
{
    return pesoKg;
}

/////////////////////////////////////////////////////////////////////////////
// GRAMAS
/////////////////////////////////////////////////////////////////////////////

float SensorBalanca::getGramas()
{
    return pesoGramas;
}

/////////////////////////////////////////////////////////////////////////////
// TARA
/////////////////////////////////////////////////////////////////////////////

void SensorBalanca::tare()
{
    balanca.tare(valorLido);

    Serial.println("--------------------------------");
    Serial.println("BALANCA ZERADA");
    Serial.println("--------------------------------");
}

/////////////////////////////////////////////////////////////////////////////
// CALIBRAÇÃO
/////////////////////////////////////////////////////////////////////////////

void SensorBalanca::calibra(float pesoConhecido)
{
    balanca.calibra(valorLido, pesoConhecido);

    Serial.println("--------------------------------");

    Serial.print("BALANCA CALIBRADA COM ");

    Serial.print(pesoConhecido);

    Serial.println(" g");

    Serial.println("--------------------------------");
}