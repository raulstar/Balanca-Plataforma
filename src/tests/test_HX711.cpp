#include <Arduino.h>
#include "HX711_Module.hpp"

/////////////////////////////////////////////////////////////////////////////
// PINOS
/////////////////////////////////////////////////////////////////////////////

#define M0 19
#define M1 21

#define m1 digitalWrite(M1, LOW)
#define m0 digitalWrite(M0, LOW)

/////////////////////////////////////////////////////////////////////////////
// UART SENSOR
/////////////////////////////////////////////////////////////////////////////

HardwareSerial SerialPort(2);

/////////////////////////////////////////////////////////////////////////////
// CLASSE SENSOR BALANÇA
/////////////////////////////////////////////////////////////////////////////

class SensorBalanca
{
private:

    //////////////////////////////////////////////////////////////////////////
    // SERIAL
    //////////////////////////////////////////////////////////////////////////

    HardwareSerial *serial;

    //////////////////////////////////////////////////////////////////////////
    // BUFFER RX
    //////////////////////////////////////////////////////////////////////////

    char rxBuffer[32];

    uint8_t rxIndex = 0;

    //////////////////////////////////////////////////////////////////////////
    // BALANÇA
    //////////////////////////////////////////////////////////////////////////

    HX711 balanca;

    //////////////////////////////////////////////////////////////////////////
    // DADOS
    //////////////////////////////////////////////////////////////////////////

    float valorLido = 0.0f;

    float pesoGramas = 0.0f;

    float pesoKg = 0.0f;

    //////////////////////////////////////////////////////////////////////////
    // STATUS
    //////////////////////////////////////////////////////////////////////////

    bool ready = false;

    bool stable = false;

    float noise = 0.0f;

    //////////////////////////////////////////////////////////////////////////
    // FILTRO
    //////////////////////////////////////////////////////////////////////////

    float mediaFiltrada = 0.0f;

    bool filtroInicializado = false;

    //////////////////////////////////////////////////////////////////////////
    // ESTABILIDADE
    //////////////////////////////////////////////////////////////////////////

    uint8_t estabilidadeCount = 0;

    //////////////////////////////////////////////////////////////////////////
    // ÚLTIMA LEITURA VÁLIDA
    //////////////////////////////////////////////////////////////////////////

    float ultimaLeitura = 0.0f;

public:

    //////////////////////////////////////////////////////////////////////////
    // CONSTRUTOR
    //////////////////////////////////////////////////////////////////////////

    SensorBalanca(HardwareSerial &porta)
    {
        serial = &porta;
    }

    //////////////////////////////////////////////////////////////////////////
    // LEITURA SENSOR
    //////////////////////////////////////////////////////////////////////////

    bool leitura()
    {
        while (serial->available())
        {
            char c = serial->read();

            //////////////////////////////////////////////////////////////////////////
            // IGNORA CR
            //////////////////////////////////////////////////////////////////////////

            if (c == '\r')
                continue;

            //////////////////////////////////////////////////////////////////////////
            // FIM DA LINHA
            //////////////////////////////////////////////////////////////////////////

            if (c == '\n')
            {
                rxBuffer[rxIndex] = '\0';

                valorLido = atof(rxBuffer);

                rxIndex = 0;

                //////////////////////////////////////////////////////////////////////////
                // IGNORA ZERO
                //////////////////////////////////////////////////////////////////////////

                if (fabs(valorLido) < 0.0001f)
                {
                    ready = false;
                    return false;
                }

                //////////////////////////////////////////////////////////////////////////
                // ANALISA RUÍDO
                //////////////////////////////////////////////////////////////////////////

                analisarRuido();

                //////////////////////////////////////////////////////////////////////////
                // PESO
                //////////////////////////////////////////////////////////////////////////

                pesoGramas = balanca.get_units(mediaFiltrada);

                pesoKg = pesoGramas / 1000.0f;

                ready = true;

                return true;
            }

            //////////////////////////////////////////////////////////////////////////
            // BUFFER RX
            //////////////////////////////////////////////////////////////////////////

            else
            {
                if (rxIndex < sizeof(rxBuffer) - 1)
                {
                    rxBuffer[rxIndex++] = c;
                }
            }
        }

        return false;
    }

private:

    //////////////////////////////////////////////////////////////////////////
    // ANÁLISE DE RUÍDO
    //////////////////////////////////////////////////////////////////////////

    void analisarRuido()
    {
        //////////////////////////////////////////////////////////////////////////
        // PRIMEIRA LEITURA
        //////////////////////////////////////////////////////////////////////////

        if (!filtroInicializado)
        {
            mediaFiltrada = valorLido;

            ultimaLeitura = valorLido;

            filtroInicializado = true;

            stable = false;

            noise = 0.0f;

            return;
        }

        //////////////////////////////////////////////////////////////////////////
        // DELTA INSTANTÂNEO
        //////////////////////////////////////////////////////////////////////////

        float deltaInstantaneo =
            fabs(valorLido - ultimaLeitura);

        //////////////////////////////////////////////////////////////////////////
        // DESCARTA SPIKES ABSURDOS
        //////////////////////////////////////////////////////////////////////////

        if (deltaInstantaneo > 0.500f)
        {
            Serial.println("SPIKE DESCARTADO");

            return;
        }

        //////////////////////////////////////////////////////////////////////////
        // FILTRO EXPONENCIAL
        //////////////////////////////////////////////////////////////////////////
        // alpha maior = resposta mais rápida
        //////////////////////////////////////////////////////////////////////////

        const float alpha = 0.35f;

        mediaFiltrada =
            (alpha * valorLido) +
            ((1.0f - alpha) * mediaFiltrada);

        //////////////////////////////////////////////////////////////////////////
        // ERRO ATUAL
        //////////////////////////////////////////////////////////////////////////

        float erro =
            fabs(valorLido - mediaFiltrada);

        //////////////////////////////////////////////////////////////////////////
        // RUÍDO
        //////////////////////////////////////////////////////////////////////////

        noise = erro;

        //////////////////////////////////////////////////////////////////////////
        // ESTABILIDADE COM HISTERESE
        //////////////////////////////////////////////////////////////////////////

        if (erro < 0.020f)
        {
            //////////////////////////////////////////////////////////////////////////
            // RECUPERA RÁPIDO
            //////////////////////////////////////////////////////////////////////////

            if (estabilidadeCount < 10)
            {
                estabilidadeCount += 2;
            }
        }
        else if (erro < 0.080f)
        {
            //////////////////////////////////////////////////////////////////////////
            // PEQUENA OSCILAÇÃO
            //////////////////////////////////////////////////////////////////////////

            if (estabilidadeCount > 0)
            {
                estabilidadeCount--;
            }
        }
        else
        {
            //////////////////////////////////////////////////////////////////////////
            // OSCILAÇÃO REAL
            //////////////////////////////////////////////////////////////////////////

            if (estabilidadeCount > 2)
            {
                estabilidadeCount -= 2;
            }
            else
            {
                estabilidadeCount = 0;
            }
        }

        //////////////////////////////////////////////////////////////////////////
        // STATUS ESTABILIDADE
        //////////////////////////////////////////////////////////////////////////

        stable = (estabilidadeCount >= 5);

        //////////////////////////////////////////////////////////////////////////
        // ATUALIZA ÚLTIMA LEITURA
        //////////////////////////////////////////////////////////////////////////

        ultimaLeitura = valorLido;
    }

public:

    //////////////////////////////////////////////////////////////////////////
    // STATUS
    //////////////////////////////////////////////////////////////////////////

    bool isReady()
    {
        return ready;
    }

    bool isStable()
    {
        return stable;
    }

    float getNoise()
    {
        return noise;
    }

    //////////////////////////////////////////////////////////////////////////
    // DADOS
    //////////////////////////////////////////////////////////////////////////

    float getRaw()
    {
        return valorLido;
    }

    float getFiltered()
    {
        return mediaFiltrada;
    }

    float getKg()
    {
        return pesoKg;
    }

    float getGramas()
    {
        return pesoGramas;
    }

    //////////////////////////////////////////////////////////////////////////
    // TARA
    //////////////////////////////////////////////////////////////////////////

    void tare()
    {
        balanca.tare(mediaFiltrada);

        Serial.println("--------------------------------");
        Serial.println("BALANCA ZERADA");
        Serial.println("--------------------------------");
    }

    //////////////////////////////////////////////////////////////////////////
    // CALIBRAÇÃO
    //////////////////////////////////////////////////////////////////////////

    void calibra(float pesoConhecido)
    {
        if (!stable)
        {
            Serial.println("ERRO: BALANCA INSTAVEL");
            return;
        }

        balanca.calibra(mediaFiltrada, pesoConhecido);

        Serial.println("--------------------------------");
        Serial.print("BALANCA CALIBRADA COM ");
        Serial.print(pesoConhecido);
        Serial.println(" g");
        Serial.println("--------------------------------");
    }
};

/////////////////////////////////////////////////////////////////////////////
// INSTÂNCIA SENSOR
/////////////////////////////////////////////////////////////////////////////

SensorBalanca sensor1(SerialPort);

/////////////////////////////////////////////////////////////////////////////
// PESO CALIBRAÇÃO
/////////////////////////////////////////////////////////////////////////////

extern float pesoCalibracao1 = 78000.0f;

/////////////////////////////////////////////////////////////////////////////
// SETUP
/////////////////////////////////////////////////////////////////////////////

void setup()
{
    pinMode(M1, OUTPUT);
    pinMode(M0, OUTPUT);

    m1;
    m0;

    Serial.begin(115200);

    SerialPort.begin(9600, SERIAL_8N1, 16, 17);

    delay(1000);

    Serial.println("\n=== SISTEMA BALANCA ===");

    Serial.println("Comandos:");
    Serial.println("t -> Tara");
    Serial.println("c -> Calibrar");

    Serial.println("========================");
}

/////////////////////////////////////////////////////////////////////////////
// LOOP
/////////////////////////////////////////////////////////////////////////////

void loop()
{
    if (sensor1.leitura())
    {
        Serial.print("RAW: ");
        Serial.print(sensor1.getRaw(), 3);

        Serial.print(" | FILT: ");
        Serial.print(sensor1.getFiltered(), 3);

        Serial.print(" | KG: ");
        Serial.print(sensor1.getKg(), 3);

        Serial.print(" | Noise: ");
        Serial.print(sensor1.getNoise(), 5);

        Serial.print(" | Stable: ");

        if (sensor1.isStable())
            Serial.print("YES");
        else
            Serial.print("NO");

        Serial.println();
    }

    //////////////////////////////////////////////////////////////////////////
    // COMANDOS SERIAL
    //////////////////////////////////////////////////////////////////////////

    if (Serial.available())
    {
        char comando = Serial.read();

        switch (comando)
        {
            //////////////////////////////////////////////////////////////////////////
            // TARA
            //////////////////////////////////////////////////////////////////////////

            case 't':
            case 'T':

                sensor1.tare();

                break;

            //////////////////////////////////////////////////////////////////////////
            // CALIBRAÇÃO
            //////////////////////////////////////////////////////////////////////////

            case 'c':
            case 'C':

                Serial.println("\nCOLOQUE O PESO DE CALIBRACAO...");

                delay(3000);

                sensor1.calibra(pesoCalibracao1);

                break;
        }
    }
}