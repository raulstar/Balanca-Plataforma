#include <Arduino.h>
#include "HX711_Module.hpp"

/////////////////////////////////////////////////////////////////////////////
// PINOS
/////////////////////////////////////////////////////////////////////////////

#define M0 19
#define M1 21

#define m1 digitalWrite(M1, LOW)
#define m0 digitalWrite(M0, LOW)

/////////////////////////////////////////////////////////////////////////////
// UART SENSOR
/////////////////////////////////////////////////////////////////////////////

HardwareSerial SerialPort(2);

/////////////////////////////////////////////////////////////////////////////
// CLASSE SENSOR BALANÇA
/////////////////////////////////////////////////////////////////////////////
class SensorBalanca
{
private:

    //////////////////////////////////////////////////////////////////////////
    // SERIAL
    //////////////////////////////////////////////////////////////////////////

    HardwareSerial *serial;

    //////////////////////////////////////////////////////////////////////////
    // BUFFER RX
    //////////////////////////////////////////////////////////////////////////

    char rxBuffer[32];

    uint8_t rxIndex = 0;

    //////////////////////////////////////////////////////////////////////////
    // BALANÇA
    //////////////////////////////////////////////////////////////////////////

    HX711 balanca;

    //////////////////////////////////////////////////////////////////////////
    // DADOS
    //////////////////////////////////////////////////////////////////////////

    float valorLido = 0.0f;

    float pesoGramas = 0.0f;

    float pesoKg = 0.0f;

    //////////////////////////////////////////////////////////////////////////
    // STATUS
    //////////////////////////////////////////////////////////////////////////

    bool ready = false;

public:

    //////////////////////////////////////////////////////////////////////////
    // CONSTRUTOR
    //////////////////////////////////////////////////////////////////////////

    SensorBalanca(HardwareSerial &porta)
    {
        serial = &porta;
    }

    //////////////////////////////////////////////////////////////////////////
    // LEITURA SENSOR
    //////////////////////////////////////////////////////////////////////////

    bool leitura()
    {
        while (serial->available())
        {
            char c = serial->read();

            //////////////////////////////////////////////////////////////////////////
            // IGNORA CR
            //////////////////////////////////////////////////////////////////////////

            if (c == '\r')
                continue;

            //////////////////////////////////////////////////////////////////////////
            // FIM DA LINHA
            //////////////////////////////////////////////////////////////////////////

            if (c == '\n')
            {
                rxBuffer[rxIndex] = '\0';

                valorLido = atof(rxBuffer);

                rxIndex = 0;

                //////////////////////////////////////////////////////////////////////////
                // IGNORA ZERO
                //////////////////////////////////////////////////////////////////////////

                if (fabs(valorLido) < 0.0001f)
                {
                    ready = false;
                    return false;
                }

                //////////////////////////////////////////////////////////////////////////
                // PESO
                //////////////////////////////////////////////////////////////////////////

                pesoGramas = balanca.get_units(valorLido);

                pesoKg = pesoGramas / 1000.0f;

                ready = true;

                return true;
            }

            //////////////////////////////////////////////////////////////////////////
            // BUFFER RX
            //////////////////////////////////////////////////////////////////////////

            else
            {
                if (rxIndex < sizeof(rxBuffer) - 1)
                {
                    rxBuffer[rxIndex++] = c;
                }
            }
        }

        return false;
    }

public:

    //////////////////////////////////////////////////////////////////////////
    // STATUS
    //////////////////////////////////////////////////////////////////////////

    bool isReady()
    {
        return ready;
    }

    //////////////////////////////////////////////////////////////////////////
    // DADOS
    //////////////////////////////////////////////////////////////////////////

    float getRaw()
    {
        return valorLido;
    }

    float getKg()
    {
        return pesoKg;
    }

    float getGramas()
    {
        return pesoGramas;
    }

    //////////////////////////////////////////////////////////////////////////
    // TARA
    //////////////////////////////////////////////////////////////////////////

    void tare()
    {
        balanca.tare(valorLido);

        Serial.println("--------------------------------");
        Serial.println("BALANCA ZERADA");
        Serial.println("--------------------------------");
    }

    //////////////////////////////////////////////////////////////////////////
    // CALIBRAÇÃO
    //////////////////////////////////////////////////////////////////////////

    void calibra(float pesoConhecido)
    {
        balanca.calibra(valorLido, pesoConhecido);

        Serial.println("--------------------------------");
        Serial.print("BALANCA CALIBRADA COM ");
        Serial.print(pesoConhecido);
        Serial.println(" g");
        Serial.println("--------------------------------");
    }
};
/////////////////////////////////////////////////////////////////////////////
// INSTÂNCIA SENSOR
/////////////////////////////////////////////////////////////////////////////

SensorBalanca sensor1(SerialPort);

/////////////////////////////////////////////////////////////////////////////
// PESO CALIBRAÇÃO
/////////////////////////////////////////////////////////////////////////////

extern float pesoCalibracao1 = 78000.0f;

/////////////////////////////////////////////////////////////////////////////
// SETUP
/////////////////////////////////////////////////////////////////////////////

void setup()
{
    pinMode(M1, OUTPUT);
    pinMode(M0, OUTPUT);

    m1;
    m0;

    Serial.begin(115200);

    SerialPort.begin(9600, SERIAL_8N1, 16, 17);

    delay(1000);

    Serial.println("\n=== SISTEMA BALANCA ===");

    Serial.println("Comandos:");
    Serial.println("t -> Tara");
    Serial.println("c -> Calibrar");

    Serial.println("========================");
}

/////////////////////////////////////////////////////////////////////////////
// LOOP
/////////////////////////////////////////////////////////////////////////////

void loop()
{
 if (sensor1.leitura())
{
    Serial.print("RAW: ");
    Serial.print(sensor1.getRaw(), 3);

    Serial.print(" | KG: ");
    Serial.print(sensor1.getKg(), 3);

    Serial.println();
}

    //////////////////////////////////////////////////////////////////////////
    // COMANDOS SERIAL
    //////////////////////////////////////////////////////////////////////////

    if (Serial.available())
    {
        char comando = Serial.read();

        switch (comando)
        {
            //////////////////////////////////////////////////////////////////////////
            // TARA
            //////////////////////////////////////////////////////////////////////////

            case 't':
            case 'T':

                sensor1.tare();

                break;

            //////////////////////////////////////////////////////////////////////////
            // CALIBRAÇÃO
            //////////////////////////////////////////////////////////////////////////

            case 'c':
            case 'C':

                Serial.println("\nCOLOQUE O PESO DE CALIBRACAO...");

                delay(3000);

                sensor1.calibra(pesoCalibracao1);

                break;
        }
    }
}